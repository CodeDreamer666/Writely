import assert from 'node:assert/strict';
import {Schema} from '@tiptap/pm/model';
import {Mapping,StepMap} from '@tiptap/pm/transform';
import {placeAnnotations,settleCard,targetAtPosition,remapConnectors,anchorPoint,connectorPath,CARD_ARROW_ANCHOR,cardArrowPoint} from '../src/annotationModel.js';
const schema=new Schema({nodes:{doc:{content:'paragraph+'},paragraph:{content:'text*',group:'block'},text:{group:'inline'}}});
const prose=(...texts)=>schema.node('doc',null,texts.map(t=>schema.node('paragraph',null,t?schema.text(t):null)));
const doc=prose('First sentence. Second thought!','A final paragraph.');
assert.equal(targetAtPosition(doc,3).quote,'First');
assert.equal(targetAtPosition(doc,5,'sentence').quote,'First sentence.');
assert.equal(targetAtPosition(doc,3,'paragraph').quote,'First sentence. Second thought!');
assert.equal(targetAtPosition(doc,0,'essay').kind,'essay');
const selection={from:17,to:31,quote:doc.textBetween(17,31,' ')};
assert.equal(targetAtPosition(doc,18,'selection',selection).quote,selection.quote);
assert.equal(targetAtPosition(prose(''),1),null);
const card={id:'a',connectors:[{id:'link',anchor:'right',target:targetAtPosition(doc,3)}]};
const insertion=new Mapping([new StepMap([1,0,5])]);
const moved=remapConnectors([card],insertion,prose('Well First sentence. Second thought!','A final paragraph.'))[0].connectors[0].target;
assert.equal(moved.from,6);assert.equal(moved.to,11);assert.equal(moved.quote,'First');assert.equal(moved.orphaned,false);
const deletion=new Mapping([new StepMap([1,5,0])]);
assert.equal(remapConnectors([card],deletion,prose(' sentence. Second thought!','A final paragraph.'))[0].connectors[0].target.orphaned,true);
const cards=[{id:'a',x:0,y:80},{id:'b',x:0,y:80},{id:'c',x:1,y:80}];
const geometry={width:1300,paperLeft:260,paperRight:1000,paperBottom:800};
const placed=placeAnnotations(cards,geometry,{a:{height:150},b:{height:120},c:{height:100}});
assert(placed.a.x+placed.a.width<geometry.paperLeft);assert(placed.c.x>geometry.paperRight);assert(placed.b.y>=placed.a.y+placed.a.height+24);
const narrow=placeAnnotations(cards,{width:390,paperLeft:24,paperRight:366,paperBottom:800});
assert(narrow.a.y>=840);assert(narrow.b.y>narrow.a.y+narrow.a.height);assert(narrow.a.x>=0&&narrow.a.x+narrow.a.width<=390);
const settled=settleCard({x:10,y:30,width:150,height:100},[{x:10,y:30,width:150,height:100}]);assert.equal(settled.y,154);
assert.deepEqual(anchorPoint({x:10,y:20,width:200,height:100},'right'),{x:210,y:70});
assert(connectorPath({x:210,y:70},{x:400,y:70},'right').startsWith('M 210 70 C'));
const rect={x:10,y:20,width:200,height:100},points={right:[.9,.45]};
assert.equal(CARD_ARROW_ANCHOR,'right');
assert.deepEqual(cardArrowPoint(rect,points),{x:190,y:65});
assert.deepEqual(cardArrowPoint({...rect,width:300,height:200},points),{x:280,y:110});
assert.deepEqual(cardArrowPoint({...rect,x:50,y:70},points),{x:230,y:115});
const legacyLinks=['top','right','bottom','left'].map((anchor,i)=>({id:String(i),anchor,target:{kind:'essay'}}));
const loadedLinks=JSON.parse(JSON.stringify(legacyLinks));
assert.deepEqual(loadedLinks,legacyLinks);
assert(loadedLinks.every(link=>connectorPath(cardArrowPoint(rect,points),{x:400,y:70},CARD_ARROW_ANCHOR).startsWith('M 190 65 C')));
console.log('Annotation tests passed: targets, mapping, deletion, margin placement, narrow shelves, collision spacing, anchors.');
